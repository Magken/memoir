import type { FieldSpec, FieldType, FilterOp, ResourceKey } from './types'

export type ResourceCatalogEntry = {
  resourceKey: ResourceKey
  allowedSelect: readonly string[]
  allowedFilter: readonly string[]
  allowedSort: readonly string[]
  allowedWrite: readonly string[]
  columnTypes: Readonly<Record<string, FieldType | string>>
  allowedFilterOps: Readonly<Record<string, readonly (FilterOp | string)[]>>
  requiredOnCreate: readonly string[]
  upsertKeys: readonly string[]
  defaultOrder: readonly { field: string; asc?: boolean }[]
  rowScope: 'owner' | 'public'
  maxLimit: number
  maxBulk: number
  canCreate: boolean
  canUpdate: boolean
  canDelete: boolean
  fields: readonly FieldSpec[]
}

function field(
  key: string,
  type: FieldType | string,
  opts: Partial<FieldSpec> & { filterOps: readonly (FilterOp | string)[] },
): FieldSpec {
  return {
    key,
    type,
    nullable: opts.nullable ?? true,
    filterOps: [...opts.filterOps],
    sortable: opts.sortable ?? false,
    writable: opts.writable ?? false,
    constraints: opts.constraints ?? {},
  }
}

