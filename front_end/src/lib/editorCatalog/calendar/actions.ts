export function calendarActionById(id: string): CalendarEditorAction | undefined {
  return CALENDAR_EDITOR_ACTIONS.find((action) => action.id === id)
}

/** Action ids the Calendar runtime must handle when implemented. */
export const CALENDAR_IMPLEMENTED_ACTION_IDS = CALENDAR_EDITOR_ACTIONS.filter((a) => a.implemented).map(
  (a) => a.id,
)
