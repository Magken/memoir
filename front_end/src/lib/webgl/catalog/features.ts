type RegistryRow = {
  id: string
  kind: string
  layer: string
  summary: string
}

export function harvestPlannedFeatures(
  registry: readonly RegistryRow[],
  built: readonly WebglFeature[],
): WebglFeature[] {
  const referenced = new Set(built.flatMap((row) => row.referenceIds))
  const builtIds = new Set(built.map((row) => row.id))
  const planned: WebglFeature[] = []
  for (const row of registry) {
    if (referenced.has(row.id) || builtIds.has(row.id)) continue
    if (!WEBGL_KIND_SET.has(row.kind) || !WEBGL_LAYER_SET.has(row.layer)) continue
    planned.push({
      id: row.id,
      label: row.id,
      kind: row.kind as WebglFeature['kind'],
      layer: row.layer as WebglFeature['layer'],
      status: 'planned',
      summary: row.summary,
      module: null,
      referenceIds: [row.id],
      knobs: [],
    })
  }
  return planned
}

export const WEBGL_PLANNED_FEATURES: readonly WebglFeature[] = harvestPlannedFeatures(
  plannedFromRegistry as RegistryRow[],
  WEBGL_BUILT_FEATURES,
)

export const WEBGL_FEATURES: readonly WebglFeature[] = [
  ...WEBGL_BUILT_FEATURES,
  ...WEBGL_PLANNED_FEATURES,
]

/** Built rows whose `module` path is missing on disk. */
export function builtModuleGaps(
  features: readonly WebglFeature[],
  exists: (repoPath: string) => boolean,
): string[] {
  return features
    .filter((row) => row.status === 'built')
    .filter((row) => !row.module || !exists(row.module))
    .map((row) => `${row.id} → ${row.module ?? '(none)'}`)
}
