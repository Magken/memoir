export type ThemeSectionId = (typeof themeSections)[number]['id']

export function themeNavLinkHref(
  nodes: readonly DocNavMenuNode[],
  id: string,
): string | undefined {
  for (const node of nodes) {
    if (node.type === 'link' && node.id === id) return node.href
    if (node.type === 'section') {
      const found = themeNavLinkHref(node.children, id)
      if (found) return found
    }
  }
  return undefined
}

